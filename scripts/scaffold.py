class Scaffolder:
    """
    TEMPLATE: Generates files for the common case.
    Add parameters that vary between projects (version, group, options, etc.)
    """

    def __init__(
        self,
        target: str,
        option_value: str = "default",   # TEMPLATE: Replace with your own options
        dry_run: bool = False,
        verbose: bool = False,
    ):
        self.target = Path(target)
        self.option_value = option_value
        self.dry_run = dry_run
        self.verbose = verbose
        self.generated: list[str] = []

    def run(self) -> dict:
        if not self.target.exists():
            raise ValueError(f"Target path does not exist: {self.target}")

        # TEMPLATE: Call _write() for each file you want to generate
        self._write(
            "example-config.yml",
            TEMPLATES["example-config.yml"].format(option_value=self.option_value),
        )

        return {"generated": self.generated, "target": str(self.target)}

    def _write(self, rel_path: str, content: str) -> None:
        dest = self.target / rel_path
        if self.verbose or self.dry_run:
            print(f"  {'[dry-run] ' if self.dry_run else ''}write → {dest}")
        if not self.dry_run:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(content)
        self.generated.append(str(dest))


