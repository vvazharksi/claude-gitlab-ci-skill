def detect_project(target: Path) -> dict:
    """
    Scan a project directory and return structured context.
    Output is designed to help an agent decide what to generate.

    TEMPLATE: Extend this to detect whatever is relevant to your domain.
    The returned dict is what the agent sees when you run `detect`.
    """
    result: dict = {
        "target":             str(target),
        "language":           None,
        "has_existing_config": False,
        "config_file":        None,
        "gaps":               [],
        "scaffold_supported": False,
    }

    files = {f.name for f in target.iterdir() if f.is_file()}

    # Language / framework detection
    for filename, lang in INDICATORS.items():
        if filename in files:
            result["language"] = lang
            break

    # Existing config detection
    # TEMPLATE: Replace "example-config.yml" with your actual config file name
    if "example-config.yml" in files:
        result["has_existing_config"] = True
        result["config_file"] = "example-config.yml"

    # Gap analysis
    result["gaps"] = _build_gap_list(result)

    # TEMPLATE: Set scaffold_supported based on what your scaffold command handles
    result["scaffold_supported"] = result["language"] == "python"

    return result


def _build_gap_list(result: dict) -> list[str]:
    """
    TEMPLATE: Return a list of human-readable gaps found in the project.
    These are shown to the agent so it knows what needs to be fixed/generated.
    """
    gaps = []
    if not result["has_existing_config"]:
        gaps.append("no config file found")
    if not result["language"]:
        gaps.append("could not detect language")
    return gaps


