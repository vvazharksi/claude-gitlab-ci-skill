def main():
    parser = argparse.ArgumentParser(
        description="[Your Skill] tool — detect project context or scaffold config files",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
commands:
  detect    scan a project directory and report language, gaps, and recommendations
  scaffold  write config files for the common case

examples:
  %(prog)s detect ./my-project
  %(prog)s detect ./my-project --json
  %(prog)s scaffold ./my-project --option-value custom --dry-run
""",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    # detect
    p_detect = subparsers.add_parser("detect", help="Scan project and report context")
    p_detect.add_argument("target", help="Project directory to scan")
    p_detect.add_argument("--json", action="store_true", dest="output_json")

    # scaffold — TEMPLATE: Add your own arguments here
    p_scaffold = subparsers.add_parser("scaffold", help="Generate config files")
    p_scaffold.add_argument("target", help="Target project directory")
    p_scaffold.add_argument("--option-value", default="default", metavar="VAL")
    p_scaffold.add_argument("--dry-run", action="store_true")
    p_scaffold.add_argument("--verbose", "-v", action="store_true")
    p_scaffold.add_argument("--json", action="store_true", dest="output_json")

    args = parser.parse_args()

    try:
        if args.command == "detect":
            target = Path(args.target)
            if not target.exists():
                raise ValueError(f"Path does not exist: {target}")
            result = detect_project(target)
            if args.output_json:
                print(json.dumps(result, indent=2))
            else:
                _print_detection(result)

        elif args.command == "scaffold":
            gen = Scaffolder(
                target=args.target,
                option_value=args.option_value,
                dry_run=args.dry_run,
                verbose=args.verbose,
            )
            result = gen.run()
            if args.output_json:
                print(json.dumps(result, indent=2))
            else:
                action = "Would generate" if args.dry_run else "Generated"
                print(f"{action} {len(result['generated'])} files in {result['target']}")
                if args.verbose or args.dry_run:
                    for f in result["generated"]:
                        print(f"  {f}")

    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)


def _print_detection(r: dict) -> None:
    print(f"Target:   {r['target']}")
    print(f"Language: {r['language'] or 'unknown'}")
    print(f"Config:   {r['config_file'] or 'none'}")
    if r["gaps"]:
        print("Gaps:")
        for g in r["gaps"]:
            print(f"  - {g}")
    print(f"Scaffold: {'supported' if r['scaffold_supported'] else 'not supported — use SKILL.md patterns for manual generation'}")


if __name__ == "__main__":
    main()
